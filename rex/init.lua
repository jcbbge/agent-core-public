-- Rex config: waiting agents, triage, fleet, inbox and Hive palette.
local HOME = os.getenv("HOME")
local ON_HIVE = HOME:sub(1, 6) == "/home/"         -- true once the server runs on hive (idea 12)
local SHELL_FLAVOR = "com.superlogical.terminal.shell"   -- CHECK: C1
HIVE = {}                                           -- global: hive.lua's actions call it
function HIVE.argv(cmd)                             -- a command line to run on hive, from wherever the server is
  if ON_HIVE then return { "sh", "-lc", cmd } end
  return { "ssh", "-t", "hive", cmd }
end
function HIVE.open(ctx, cmd, title)
  local _, err = rex.session.new_window{ session_id = ctx.session_id, window_label = title, focus = true,
    layout = rex.layout.block{ flavor = SHELL_FLAVOR, options = { command = HIVE.argv(cmd) } } }
  if err then error(err, 0) end
end
pcall(require, "hive")                              -- generated by rex-hive-sync; absent is fine

rex.action{ name = "hive_refresh", title = "Refresh Hive Menu", category = "Hive",
  keywords = "launch menu sync reload hive",
  run = function()
    local h, err = rex.exec.start({ HOME .. "/.local/bin/rex-hive-sync" }, { detach = true })
    if not h then error(err, 0) end
    return { message = "Refreshing the Hive menu…" }
  end }

rex.action{ name = "spawn_agent", title = "Start an Agent…", category = "Hive",
  keywords = "agent claude spawn start brief new",
  args = { name = "string", brief = "string" },
  run = function(ctx, args)
    if not args.name:match("^[a-z0-9][a-z0-9-]*$") then error("name: lowercase letters, digits and dashes", 0) end
    local r, err = rex.exec({ HOME .. "/.local/bin/agent-launch", ctx.session_id, ctx.block_id or "", args.name },
      { stdin = args.brief, timeout = 25 })
    if not r then error(err, 0) end
    if not r.ok then error(r.stderr ~= "" and r.stderr or "agent-launch failed", 0) end
    return { message = "Started " .. args.name .. " (reports to the pane you launched it from)." }
  end }

local T = "com.superlogical.terminal"
local STATE = os.getenv("XDG_STATE_HOME") or (HOME .. "/.local/state")
local rank = { blocked = 1, error = 2, done = 3 }
local function view(sid)
  return rex.call("session.view", { session_id = sid }) or {} -- CHECK: rex api describe session.view --json (C4)
end
local function focused(v)
  for _, w in ipairs(v.windows or {}) do
    if w.window_id == v.active_window_id then return w.focused_block_id end
  end
end
local function holds(node, bid)
  if not node then return false end
  if node.block then return node.block.block_id == bid end
  if node.split then return holds(node.split.before, bid) or holds(node.split.after, bid) end
  return false
end
local function blocks(sid)
  return (rex.call("session.list_blocks", { session_id = sid }) or {}).blocks or {} -- CHECK: rex api describe session.list_blocks --json (C5)
end
rex.action{
  name = "next_waiting", title = "Next Agent Waiting on Me", category = "Agents",
  keywords = "waiting blocked agent attention next", args = { direction = "string?" },
  run = function(ctx, args)
    local found = {}
    for _, s in ipairs((rex.call("session.list") or {}).sessions or {}) do
      for _, b in ipairs(blocks(s.session_id)) do
        if b.creator_name == T then
          local status = rex.call(T .. ".program_status", { session_id = s.session_id, block_id = b.block_id }) -- CHECK: rex api describe com.superlogical.terminal.program_status --json (C6)
          for _, r in ipairs((status or {}).records or {}) do
            if (r.id == nil or r.id == "") and rank[r.state] then
              table.insert(found, { sid = s.session_id, bid = b.block_id, placement = b.placement,
                rank = rank[r.state], at = r.updated_at or "" })
            end
          end
        end
      end
    end
    if #found == 0 then return { message = "Nothing is waiting on you." } end
    table.sort(found, function(a, b)
      if a.rank ~= b.rank then return a.rank < b.rank end
      if a.at ~= b.at then return a.at < b.at end
      return a.bid < b.bid
    end)
    local prev = args.direction == "prev"
    local index = prev and #found or 1
    for i, b in ipairs(found) do
      if b.bid == ctx.block_id and b.sid == ctx.session_id then
        index = ((i - 1 + (prev and -1 or 1)) % #found) + 1
        break
      end
    end
    local f = found[index]
    if f.placement == "detached" then
      local anchor = f.sid == ctx.session_id and ctx.block_id or focused(view(f.sid))
      local _, err = rex.session.move_block{ session_id = f.sid, block_id = f.bid, anchor_block_id = anchor,
        direction = "vertical", side = "after", ratio = 0.6 }
      if err then error(err, 0) end
    end
    local _, err = rex.session.focus_block{ session_id = f.sid, block_id = f.bid }
    if err then error(err, 0) end
    if f.sid ~= ctx.session_id then
      pcall(rex.client.queue, "session.select", { session_id = f.sid }) -- CHECK: rex -C <app client> actions --json (C10)
    end
  end
}
rex.action{ name = "fleet_dismiss", title = "Send Agent Out of Sight", category = "Agents",
  run = function(ctx)
    local f = ctx.block_id and io.open(STATE .. "/rex-fleet/" .. ctx.block_id:match("[^:]+$") .. ".anchor")
    if not f then return { message = "This pane is not a fleet agent." } end
    f:close()
    return rex.session.detach_block{ session_id = ctx.session_id, block_id = ctx.block_id }
  end }
rex.action{ name = "inbox_toggle", title = "Show or Hide the Inbox", category = "Agents",
  run = function(ctx)
    local inboxes = {}
    for _, b in ipairs(blocks(ctx.session_id)) do if b.label == "inbox" then inboxes[b.block_id] = true end end
    local v = view(ctx.session_id)
    for _, w in ipairs(v.windows or {}) do
      if w.window_id == v.active_window_id then
        for _, l in ipairs(w.layers or {}) do
          for bid in pairs(inboxes) do
            if holds(l.layout, bid) then
              return rex.session.set_layer_state{ session_id = ctx.session_id, layer_id = l.layer_id,
                state = l.state == "minimized" and "normal" or "minimized" }
            end
          end
        end
      end
    end
  end }
